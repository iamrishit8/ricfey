/**
 * Build docs/phase-1-cost-report.md from every docs/samples/<skill>/<model>/usage.json.
 *   bun run cost:report [-- --usd-inr 84.5 --usd-inr-source "RBI reference rate, 2026-10-20"]
 * Fake-provider samples are skipped unless --include-fake (used only to test this script).
 */
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { costSample, type SampleUsage } from '../src/llm/cost';
import { FUTURE_PRICE_DATE, PRICING_READ_ON, PRICING_SOURCE } from '../src/llm/pricing';

const REPO_ROOT = resolve(import.meta.dir, '../../..');
const RATE_LIMITS_SOURCE = 'https://ai.google.dev/gemini-api/docs/rate-limits';

const { values } = parseArgs({
  options: {
    samples: { type: 'string', default: join(REPO_ROOT, 'docs/samples') },
    out: { type: 'string', default: join(REPO_ROOT, 'docs/phase-1-cost-report.md') },
    'usd-inr': { type: 'string' },
    'usd-inr-source': { type: 'string' },
    'include-fake': { type: 'boolean', default: false },
  },
});

const usdInr = values['usd-inr'] ? Number(values['usd-inr']) : null;
if (usdInr !== null && (!Number.isFinite(usdInr) || !values['usd-inr-source'])) {
  console.error('--usd-inr needs a number and --usd-inr-source saying where the rate came from.');
  process.exit(2);
}

const samples: SampleUsage[] = [];
for await (const path of new Bun.Glob('*/*/usage.json').scan(values.samples)) {
  const u = (await Bun.file(join(values.samples, path)).json()) as SampleUsage;
  if (u.provider === 'fake' && !values['include-fake']) continue;
  samples.push(u);
}
if (samples.length === 0) {
  console.error(`No usable samples under ${values.samples}. Run gen:sample first.`);
  process.exit(1);
}
samples.sort((a, b) => a.model.localeCompare(b.model) || a.skill.localeCompare(b.skill));

const today = new Date();
const future = new Date(`${FUTURE_PRICE_DATE}T00:00:00Z`);
const todayLabel = today.toISOString().slice(0, 10);

const usd = (n: number) => (n < 0.01 ? `$${n.toFixed(5)}` : `$${n.toFixed(4)}`);
const inr = (n: number) => (usdInr ? ` (₹${(n * usdInr).toFixed(2)})` : '');
const pct = (part: number, whole: number) => (whole ? `${Math.round((part / whole) * 100)}%` : '–');

const rows = samples.map((u) => ({ u, now: costSample(u, today), fut: costSample(u, future) }));

const perSample = rows
  .map(({ u, now, fut }) => {
    const retries = now.outline.calls + now.day.calls - 2;
    return (
      `| ${u.skill} | \`${u.model}\` | ${now.outline.tokensIn} / ${now.outline.tokensOut} | ` +
      `${now.day.tokensIn} / ${now.day.tokensOut} | ${pct(now.day.tokensThinking, now.day.tokensOut)} | ` +
      `${retries} | ${usd(fut.costPerCourseDayUsd)} | ${usd(now.costPerCourseDayUsd)} |`
    );
  })
  .join('\n');

const models = [...new Set(samples.map((s) => s.model))];
const perModel = models
  .map((m) => {
    const mine = rows.filter((r) => r.u.model === m);
    const avg = (f: (r: (typeof rows)[number]) => number) =>
      mine.reduce((s, r) => s + f(r), 0) / mine.length;
    const fut30 = avg((r) => r.fut.course30DaysUsd);
    const now30 = avg((r) => r.now.course30DaysUsd);
    const futDay = avg((r) => r.fut.costPerCourseDayUsd);
    return `| \`${m}\` | ${mine.length} | ${usd(futDay)}${inr(futDay)} | **${usd(fut30)}${inr(fut30)}** | ${usd(now30)}${inr(now30)} |`;
  })
  .join('\n');

const report = `# Phase 1 cost report

Generated ${todayLabel} by \`bun run cost:report\` from ${samples.length} samples in \`docs/samples/\`.
Do not edit the tables by hand; re-run the script.

## Method

- Each sample = one course outline + day 1, generated by \`bun run gen:sample\`.
- Tokens are Gemini's own counts (\`usageMetadata\`). Output includes thinking tokens, which
  are billed as output. Every call counts, including retries and failed attempts.
- **Cost per course-day** = day-1 cost + (outline cost ÷ days in that course).
- **30-day course** = outline cost per day × 30 + day-1 cost × 30. Day 1 stands in for every day.
- Prices: paid-tier standard prices from ${PRICING_SOURCE} (read ${PRICING_READ_ON}).
  **Primary figures use prices from ${FUTURE_PRICE_DATE}**; prices on ${todayLabel} shown beside them.
  The free tier costs nothing but has daily limits (below) and different data terms.
${usdInr ? `- INR at ₹${usdInr} per USD (${values['usd-inr-source']}).\n` : ''}
## Per sample

| Skill | Model | Outline tokens in / out | Day tokens in / out | Thinking share of day output | Retries | $/course-day from ${FUTURE_PRICE_DATE} | $/course-day on ${todayLabel} |
| --- | --- | --- | --- | --- | --- | --- | --- |
${perSample}

## 30-day course, averaged over skills

| Model | Samples | $/course-day from ${FUTURE_PRICE_DATE} | 30-day course from ${FUTURE_PRICE_DATE} | 30-day course on ${todayLabel} |
| --- | --- | --- | --- | --- |
${perModel}

## Free-tier limits

The docs do not publish per-model free-tier numbers: "Rate limits depend on a variety of
factors (such as your usage tier) and can be viewed in Google AI Studio"
(${RATE_LIMITS_SOURCE}). Requests per day reset at midnight Pacific time (same page).
Fill in from AI Studio → rate limits, for this account:

| Model | RPM | TPM (input) | RPD | Course-days/day on free tier ≈ RPD ÷ calls per day |
| --- | --- | --- | --- | --- |
${models.map((m) => `| \`${m}\` | _fill in_ | _fill in_ | _fill in_ | _fill in_ |`).join('\n')}

Free-tier content is "used to improve our products"; paid-tier content is not (${PRICING_SOURCE}).

## Caveats

- One sample per skill and model: token counts vary run to run.
- Day 1 may be shorter or longer than later days.
- Prices change; they live in \`apps/api/src/llm/pricing.ts\` with their source and read date.
`;

await Bun.write(values.out, report);
console.info(`Wrote ${values.out} (${samples.length} samples, models: ${models.join(', ')})`);
